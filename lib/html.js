/**
 * dsh-session-forward · 转发网页渲染（零依赖纯函数）
 *
 * 把一份 bundle + 已渲染好的 Markdown 变成一个**完全自包含**的 HTML 页面：
 * 内联样式、内联脚本、不引用任何外部资源、不联网。接收方双击就能在任何浏览器里读，
 * 页面底部的按钮可以把全文复制成 Markdown 拿回自己的 DSH 继续聊。
 *
 * 文案按内容语言自动选中文/英文（不依赖 Host 侧的 i18n 服务）。
 */

const CJK = /[\u3400-\u9fff\uf900-\ufaff]/

/**
 * HTML 转义：正文、标题、内嵌 Markdown 都必须过这一层。
 * @param {unknown} text
 * @returns {string}
 */
export function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

/**
 * 从「会话文件名」或「标题」推导网页文件名。
 * @param {string} source
 * @returns {string}
 */
export function suggestHtmlFileName(source) {
  const raw = typeof source === 'string' ? source : ''
  const stripped = raw.replace(/\.dshchat\.json$/i, '').replace(/\.json$/i, '').trim()
  return `${stripped === '' ? 'dsh-session' : stripped}.dshchat.html`
}

/**
 * 内容语言启发式：标题与正文里 CJK 字符占比足够高就用中文文案。
 * @param {string} title
 * @param {ReadonlyArray<{ text?: unknown }>} messages
 * @returns {'zh' | 'en'}
 */
function contentLanguage(title, messages) {
  const sample = [title]
    .concat(messages.map((message) => (typeof message.text === 'string' ? message.text : '')))
    .join('\n')
    .slice(0, 20000)
  if (sample === '') return 'en'
  let cjk = 0
  let latin = 0
  for (const char of sample) {
    if (CJK.test(char)) cjk += 1
    else if (/[A-Za-z]/.test(char)) latin += 1
  }
  const total = cjk + latin
  if (total === 0) return 'en'
  return cjk / total > 0.08 ? 'zh' : 'en'
}

const LABELS = {
  zh: {
    user: '我',
    assistant: '助手',
    copy: '复制全文（Markdown）',
    copied: '已复制',
    footer: '由 DeepSeek Harness · 会话转发生成',
    meta: (when, count) => `转发自 DSH · ${when} · ${count} 条消息`,
    note: '这是一段从 DSH 会话里导出的对话记录。双击文件即可阅读，不需要安装任何东西；页面底部的按钮可以把全文复制成 Markdown。',
    source: (session) => (session === '' ? '' : `来源会话：${session}`),
    expires: (when) => `这个分享链接有效期至 ${when}。`,
  },
  en: {
    user: 'Me',
    assistant: 'Assistant',
    copy: 'Copy full text (Markdown)',
    copied: 'Copied',
    footer: 'Generated by DeepSeek Harness · Session forwarding',
    meta: (when, count) => `Forwarded from DSH · ${when} · ${count} messages`,
    note: 'A conversation record exported from a DSH session. Double-click the file to read it — nothing to install. The button at the bottom copies the whole text as Markdown.',
    source: (session) => (session === '' ? '' : `Source session: ${session}`),
    expires: (when) => `This share link stays valid until ${when}.`,
  },
}

function formatWhen(bundle) {
  const iso = typeof bundle.exportedAtIso === 'string' ? bundle.exportedAtIso : ''
  if (iso.length >= 16) return iso.slice(0, 16).replace('T', ' ')
  const stamp = typeof bundle.exportedAt === 'number' ? bundle.exportedAt : Date.now()
  try {
    return new Date(stamp).toLocaleString(undefined, {
      year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
    })
  } catch {
    return new Date(stamp).toISOString().slice(0, 16).replace('T', ' ')
  }
}

function formatExpiry(expiresAt) {
  if (!Number.isFinite(expiresAt)) return ''
  try {
    return new Date(expiresAt).toLocaleString(undefined, {
      year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
    })
  } catch {
    return new Date(expiresAt).toISOString().slice(0, 16).replace('T', ' ')
  }
}

/**
 * 渲染转发网页。
 *
 * @param {object} options
 * @param {object} options.bundle 转发 bundle（messages 数组必需）
 * @param {string} [options.markdown] 已有 Markdown 文本；缺省时按消息现拼一份
 * @param {string} [options.title] 覆盖 bundle 里的标题
 * @param {string} [options.sessionId] 来源会话 id（仅展示）
 * @param {number} [options.expiresAt] 分享链接过期时间（毫秒）；给了就在页脚标注有效期
 * @returns {string} 完整 HTML
 */
export function renderHtmlDocument(options) {
  const bundle = options?.bundle ?? {}
  const messages = Array.isArray(bundle.messages) ? bundle.messages : []
  const rawTitle = typeof options?.title === 'string' && options.title.trim() !== ''
    ? options.title.trim()
    : (typeof bundle.session?.title === 'string' && bundle.session.title.trim() !== '')
      ? bundle.session.title.trim()
      : ''
  const lang = contentLanguage(rawTitle, messages)
  const labels = LABELS[lang]
  const title = escapeHtml(rawTitle === '' ? (lang === 'zh' ? '未命名会话' : 'Untitled session') : rawTitle)
  const markdown = typeof options?.markdown === 'string' && options.markdown !== ''
    ? options.markdown
    : renderMarkdown(bundle, labels)
  const when = escapeHtml(formatWhen(bundle))
  const meta = escapeHtml(labels.meta(when, messages.length))
  const sessionId = typeof options?.sessionId === 'string' ? options.sessionId : ''
  const source = escapeHtml(labels.source(sessionId))
  const expiry = Number.isFinite(options?.expiresAt) && options.expiresAt > 0
    ? escapeHtml(labels.expires(options.expiresAt))
    : ''

  const body = messages.map((message) => {
    const mine = message?.role === 'user'
    const text = escapeHtml(typeof message?.text === 'string' ? message.text : '')
    return [
      `<article class="msg ${mine ? 'msg-user' : 'msg-assistant'}">`,
      `<div class="who">${message?.role === 'user' ? labels.user : labels.assistant}</div>`,
      `<div class="text">${text}</div>`,
      '</article>',
    ].join('')
  }).join('\n')

  return [
    '<!doctype html>',
    '<html>',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<meta name="color-scheme" content="light dark">',
    '<meta name="robots" content="noindex, nofollow">',
    `<title>${title}</title>`,
    '<style>',
    ':root{color-scheme:light dark}',
    '*{box-sizing:border-box}',
    'body{margin:0;background:#f6f7f9;color:#1b1d22;font:16px/1.65 -apple-system,BlinkMacSystemFont,"Segoe UI","PingFang SC","Hiragino Sans GB","Microsoft YaHei",sans-serif}',
    '.wrap{max-width:760px;margin:0 auto;padding:40px 20px 72px}',
    '.head{border-bottom:1px solid #e3e6ea;padding-bottom:18px;margin-bottom:28px}',
    'h1{margin:0 0 8px;font-size:26px;line-height:1.3;letter-spacing:.01em}',
    '.meta{margin:0;color:#6b7280;font-size:13px}',
    '.note{margin:14px 0 0;padding:10px 14px;border-radius:10px;background:#eef2ff;color:#38418a;font-size:13px}',
    '.msg{margin:0 0 18px;padding:14px 16px;border-radius:14px;background:#fff;border:1px solid #e6e8ec}',
    '.msg-user{background:#f0f4ff;border-color:#dbe4ff}',
    '.who{font-size:12px;font-weight:600;letter-spacing:.04em;text-transform:uppercase;color:#6b7280;margin-bottom:6px}',
    '.text{white-space:pre-wrap;overflow-wrap:anywhere}',
    '.foot{margin-top:34px;border-top:1px solid #e3e6ea;padding-top:18px;color:#6b7280;font-size:13px}',
    'button{font:inherit;font-size:14px;padding:8px 14px;border-radius:10px;border:1px solid #cfd4dc;background:#fff;color:#1b1d22;cursor:pointer}',
    'button:hover{background:#f2f4f7}',
    '#dshsf-md{display:none}',
    '@media (prefers-color-scheme:dark){',
    'body{background:#14161a;color:#e8eaee}',
    '.msg{background:#1b1e23;border-color:#2a2f36}',
    '.msg-user{background:#1a2333;border-color:#26354d}',
    '.head,.foot{border-color:#2a2f36}',
    '.meta,.who,.foot{color:#9aa2ad}',
    '.note{background:#1d2330;color:#a9b6e8}',
    'button{background:#1b1e23;border-color:#343a43;color:#e8eaee}',
    'button:hover{background:#232830}',
    '}',
    '@media print{body{background:#fff;color:#000}.note,button{display:none}.msg{break-inside:avoid}}',
    '</style>',
    '</head>',
    '<body>',
    '<div class="wrap">',
    '<header class="head">',
    `<h1>${title}</h1>`,
    `<p class="meta">${meta}</p>`,
    `<p class="note">${escapeHtml(labels.note)}</p>`,
    '</header>',
    '<main>',
    body,
    '</main>',
    '<footer class="foot">',
    `<button id="dshsf-copy" type="button">${escapeHtml(labels.copy)}</button>`,
    `<pre id="dshsf-md">${escapeHtml(markdown)}</pre>`,
    `<p>${escapeHtml(labels.footer)}</p>`,
    source === '' ? '' : `<p class="meta">${source}</p>`,
    expiry === '' ? '' : `<p class="meta">${expiry}</p>`,
    '</footer>',
    '</div>',
    '<script>',
    '(function(){',
    'var button=document.getElementById("dshsf-copy");',
    'var source=document.getElementById("dshsf-md");',
    'if(!button||!source)return;',
    'var label=button.textContent;',
    'function restore(){window.setTimeout(function(){button.textContent=label},1600)}',
    `function done(){button.textContent=${JSON.stringify(labels.copied)};restore()}`,
    'function fallback(){',
    'var area=document.createElement("textarea");',
    'area.value=source.textContent||"";',
    'document.body.appendChild(area);',
    'area.select();',
    'try{document.execCommand("copy");done()}catch(e){}',
    'if(area.parentNode)area.parentNode.removeChild(area);',
    '}',
    'button.addEventListener("click",function(){',
    'var text=source.textContent||"";',
    'if(navigator.clipboard&&navigator.clipboard.writeText){navigator.clipboard.writeText(text).then(done,fallback)}else{fallback()}',
    '});',
    '}());',
    '</script>',
    '</body>',
    '</html>',
  ].filter((line) => line !== '').join('\n')
}

/** 没给 markdown 时按消息拼一份（角色名跟随内容语言） */
function renderMarkdown(bundle, labels) {
  const title = typeof bundle.session?.title === 'string' ? bundle.session.title : ''
  const lines = [`# ${title}`, '']
  for (const message of Array.isArray(bundle.messages) ? bundle.messages : []) {
    lines.push(message?.role === 'user' ? `**${labels.user}**` : `**${labels.assistant}**`)
    lines.push('')
    lines.push(String(message?.text ?? ''))
    lines.push('')
  }
  return lines.join('\n')
}
