#!/usr/bin/env node
/**
 * dsh-session-forward · 转发网页渲染（Host 侧 lib/html.js）离线测试
 *
 * 运行：
 *   ELECTRON_RUN_AS_NODE=1 "/Applications/DeepSeek Harness.app/Contents/MacOS/DeepSeek Harness" test/html-host.mjs
 */

import { renderHtmlDocument, suggestHtmlFileName, escapeHtml } from '../lib/html.js'

let passed = 0
let failed = 0
const failures = []

function ok(condition, label, detail) {
  if (condition) {
    passed += 1
    return
  }
  failed += 1
  failures.push(detail === undefined ? label : `${label}（${detail}）`)
}
function contains(haystack, needle, label) {
  ok(haystack.includes(needle), label, `缺少 ${JSON.stringify(needle.slice(0, 60))}`)
}
function excludes(haystack, needle, label) {
  ok(!haystack.includes(needle), label, `不应出现 ${JSON.stringify(needle.slice(0, 60))}`)
}

/* ---------- 中文会话（默认路径） ---------- */

const zhBundle = {
  format: 'dsh-session-forward',
  version: 1,
  exportedAt: 1793700000000,
  exportedAtIso: '2026-11-03T10:00:00.000Z',
  session: { title: '<script>alert("title")</script>', messageCount: 2 },
  messages: [
    { role: 'user', text: '你好 <img src=x onerror="alert(1)"> & "引号"' },
    { role: 'assistant', text: '第一行\n第二行 </article><script>alert(2)</script>' },
  ],
}

const zhHtml = renderHtmlDocument({
  bundle: zhBundle,
  markdown: '# 标题\n\n**我**\n\n</pre><script>alert(3)</script>',
  sessionId: 'session-abc',
})

ok(zhHtml.startsWith('<!doctype html>'), '以 doctype 开头')
contains(zhHtml, '<meta charset="utf-8">', '声明 UTF-8')
contains(zhHtml, '<meta name="robots" content="noindex, nofollow">', '声明不被索引')
contains(zhHtml, '<title>&lt;script&gt;alert(&quot;title&quot;)&lt;/script&gt;</title>', '标题被转义')
excludes(zhHtml, '<title><script>', '标题里没有未转义的 script')

contains(zhHtml, 'class="msg msg-user"', '用户消息有独立样式')
contains(zhHtml, 'class="msg msg-assistant"', '助手消息有独立样式')
contains(zhHtml, '你好 &lt;img src=x onerror=&quot;alert(1)&quot;&gt; &amp; &quot;引号&quot;', '消息正文被完整转义')
contains(zhHtml, '第一行\n第二行 &lt;/article&gt;&lt;script&gt;alert(2)&lt;/script&gt;', '多行正文保留换行且转义')
excludes(zhHtml, 'alert(2)</script>', '正文里没有可执行的 script')

contains(zhHtml, '2 条消息', '元信息里带消息条数')
contains(zhHtml, '2026-11-03 10:00', '元信息里带导出时间')
contains(zhHtml, '来源会话：session-abc', '带来源会话 id')
contains(zhHtml, '由 DeepSeek Harness · 会话转发生成', '带生成标记')
contains(zhHtml, '<div class="who">我</div>', '中文内容用中文角色名')
contains(zhHtml, '<div class="who">助手</div>', '中文内容用中文助手名')

contains(zhHtml, 'prefers-color-scheme:dark', '带深色模式样式')
contains(zhHtml, '@media print', '带打印样式')
contains(zhHtml, 'id="dshsf-copy"', '带复制按钮')
contains(zhHtml, '复制全文（Markdown）', '复制按钮有中文文案')
contains(zhHtml, 'id="dshsf-md"', '内嵌 Markdown 容器')
contains(zhHtml, '&lt;/pre&gt;&lt;script&gt;alert(3)&lt;/script&gt;', '内嵌 Markdown 被转义')
ok((zhHtml.match(/<\/pre>/g) ?? []).length === 1, '只有一个 </pre> 闭合标签', String((zhHtml.match(/<\/pre>/g) ?? []).length))

// 完全自包含
ok(!/<link\b/i.test(zhHtml), '没有 <link> 外部样式')
ok(!/<img\b/i.test(zhHtml), '没有任何 <img> 标签')
ok(!/<script[^>]*\bsrc\s*=/i.test(zhHtml), '内联脚本没有 src')
ok(!/https?:\/\//i.test(zhHtml), '没有任何 http(s) URL')
ok(!/@import/i.test(zhHtml), 'CSS 里没有 @import')

// 有效期（分享链接才有）
const withExpiry = renderHtmlDocument({ bundle: zhBundle, sessionId: 's1', expiresAt: 1793707200000 })
ok(/有效期至/.test(withExpiry), '给了 expiresAt 就标注有效期')
ok(/有效期至/.test(withExpiry) && !/有效期至/.test(renderHtmlDocument({ bundle: zhBundle })), '不给 expiresAt 时不标注有效期')

/* ---------- 英文会话：文案跟随内容语言 ---------- */

const enBundle = {
  format: 'dsh-session-forward',
  version: 1,
  exportedAt: 1793700000000,
  exportedAtIso: '2026-11-03T10:00:00.000Z',
  session: { title: 'Session forwarding design' },
  messages: [
    { role: 'user', text: 'Can the recipient read this without installing anything?' },
    { role: 'assistant', text: 'Yes — it is a single self-contained HTML page.' },
  ],
}
const enHtml = renderHtmlDocument({ bundle: enBundle })
contains(enHtml, '<div class="who">Me</div>', '英文内容用英文角色名')
contains(enHtml, 'Copy full text (Markdown)', '英文内容用英文按钮')
contains(enHtml, 'Forwarded from DSH', '英文元信息')
contains(enHtml, 'Generated by DeepSeek Harness', '英文页脚')
contains(enHtml, '2 messages', '英文消息计数')
ok(!/我|助手/.test(enHtml), '英文内容里不出现中文标签')

/* ---------- 文件名推导 ---------- */

ok(suggestHtmlFileName('测试会话.dshchat.json') === '测试会话.dshchat.html', '网页文件名由 .dshchat.json 推导')
ok(suggestHtmlFileName('a.json') === 'a.dshchat.html', '普通 .json 文件名也能推导')
ok(suggestHtmlFileName('一个标题') === '一个标题.dshchat.html', '标题也能推导')
ok(suggestHtmlFileName('') === 'dsh-session.dshchat.html', '空串有兜底')
ok(suggestHtmlFileName(undefined) === 'dsh-session.dshchat.html', 'undefined 有兜底')

/* ---------- 转义函数与空会话 ---------- */

ok(escapeHtml(`<>&"'`) === '&lt;&gt;&amp;&quot;&#39;', '转义覆盖五类字符')
ok(escapeHtml('a\nb') === 'a\nb', '转义不改变换行')

const emptyHtml = renderHtmlDocument({ bundle: { messages: [], session: { title: 'x' } } })
ok(emptyHtml.includes('<!doctype html>'), '空消息也能生成页面')
ok(!emptyHtml.includes('class="msg msg-user"'), '空消息不产生气泡')

/* ---------- 汇总 ---------- */

console.log(`PASS ${passed}  FAIL ${failed}`)
if (failed > 0) {
  console.log('\n失败明细:')
  for (const item of failures) console.log(`  ✗ ${item}`)
  process.exit(1)
}
